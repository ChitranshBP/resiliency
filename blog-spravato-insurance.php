                            <h2>What Is Spravato and How Does It Work?</h2>
                            <p><a href="https://en.wikipedia.org/wiki/Esketamine" target="_blank" rel="nofollow noindex">Spravato (esketamine)</a> is an FDA-approved nasal spray derived from ketamine, indicated for:</p>
                            <ul>
                                <li>Treatment-resistant depression (TRD)</li>
                                <li>Major depressive disorder with suicidal ideation (in certain cases)</li>
                            </ul>

                            <p>It works by:</p>
                            <ul>
                                <li>Modulating the glutamate system</li>
                                <li>Promoting synaptic connectivity</li>
                                <li>Delivering rapid symptom relief (often within hours to days)</li>
                            </ul>
                            <p>This makes it fundamentally different from traditional antidepressants.</p>

                            <h2>When Is Spravato Covered by Insurance?</h2>
                            <p>Most insurance plans cover Spravato when clinical criteria are met.</p>
                            <p><strong>Typical requirements include:</strong></p>

                            <h3>1. Diagnosis</h3>
                            <ul>
                                <li>Major Depressive Disorder</li>
                                <li>Treatment-resistant depression</li>
                            </ul>

                            <h3>2. Prior Treatment History</h3>
                            <ul>
                                <li>Trial of at least 2 antidepressants</li>
                                <li>Sometimes psychotherapy documentation</li>
                            </ul>

                            <h3>3. Supervised Administration</h3>
                            <p>Spravato must be administered in a certified clinic under the REMS program:</p>
                            <ul>
                                <li>In-clinic dosing</li>
                                <li>~2-hour monitoring period</li>
                            </ul>
                            <p>Because of this structure, insurance typically covers:</p>
                            <ul>
                                <li>Medication</li>
                                <li>Clinical administration</li>
                                <li>Monitoring</li>
                            </ul>

