                            <p>If you're considering Spravato® for treatment-resistant <a href="depression" class="content-link">depression</a>, one of the first questions you may have is: How long are Spravato® treatments? The answer depends on whether you're referring to the length of an individual appointment or the overall treatment program.</p>
                            
                            <p>While each Spravato® session requires several hours of monitoring, the full treatment process typically occurs over multiple weeks and is customized to each patient's needs.</p>
                            
                            <p>At Resiliency Mind + Body Medicine®, we help patients throughout <a href="newport-beach" class="content-link">Newport Beach</a>, <a href="san-juan-capistrano" class="content-link">San Juan Capistrano</a>, and Orange County understand what to expect before beginning Spravato® treatment, including scheduling, <a href="insurance" class="content-link">insurance coverage</a>, and long-term care planning.</p>

                            <h2>What Is Spravato®?</h2>
                            <p>Spravato® (esketamine) is an FDA-approved prescription nasal spray used in combination with an oral antidepressant for adults with:</p>
                            <ul>
                                <li>Treatment-resistant depression (TRD)</li>
                                <li>Major depressive disorder with acute suicidal thoughts or behaviors</li>
                            </ul>
                            
                            <p>Unlike traditional antidepressants that may take weeks to show improvement, Spravato® works differently by targeting glutamate pathways in the brain, offering a novel approach to depression treatment.</p>
                            
                            <p>Because Spravato® can temporarily affect alertness, perception, and blood pressure, treatment must be administered in a certified healthcare setting under medical supervision.</p>

                            <h2>How Long Does a Spravato® Appointment Take?</h2>
                            <p>Most Spravato® appointments last approximately 2 hours. The appointment generally includes:</p>
                            
                            <h3>Pre-Treatment Check-In</h3>
                            <p>Before treatment begins, your care team will:</p>
                            <ul>
                                <li>Review symptoms</li>
                                <li>Check vital signs</li>
                                <li>Confirm treatment readiness</li>
                                <li>Address any concerns or questions</li>
                            </ul>
                            
                            <h3>Administration of Spravato®</h3>
                            <p>Patients self-administer the nasal spray under medical supervision. The administration process itself usually takes only a few minutes.</p>
                            
                            <h3>Observation and Monitoring Period</h3>
                            <p>After receiving Spravato®, patients remain in the clinic for monitoring. This observation period is required because some individuals may experience temporary side effects such as:</p>
                            <ul>
                                <li>Dizziness</li>
                                <li>Sleepiness</li>
                                <li>Dissociation</li>
                                <li>Increased blood pressure</li>
                                <li>Mild nausea</li>
                            </ul>
                            <p>Most effects gradually improve during the observation period.</p>
                            
                            <h3>Discharge Evaluation</h3>
                            <p>Before leaving, the treatment team ensures you are medically stable and ready to return home. Because of the medication's effects, patients cannot drive themselves home after treatment and should arrange transportation in advance.</p>

