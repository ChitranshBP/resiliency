                            <p>While each Spravato® appointment typically lasts around two hours, the overall treatment journey extends across several weeks and is individualized based on your progress and clinical needs. Understanding the treatment schedule, monitoring requirements, insurance options, and available savings programs can help you make an informed decision about whether Spravato® is right for you.</p>
