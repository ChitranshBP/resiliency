                            <h2>Functional Impact of OCD</h2>
                            <p>OCD can affect multiple domains of life:</p>

                            <h3>1. Work and Productivity</h3>
                            <ul>
                                <li>Difficulty completing tasks due to repetitive behaviors</li>
                                <li>Missed deadlines or absenteeism</li>
                            </ul>

                            <h3>2. Relationships</h3>
                            <ul>
                                <li>Strain due to rituals or reassurance-seeking</li>
                                <li>Social withdrawal</li>
                            </ul>

                            <h3>3. Daily Living</h3>
                            <ul>
                                <li>Difficulty leaving the house</li>
                                <li>Prolonged routines (e.g., hours spent checking or cleaning)</li>
                            </ul>

                            <h3>4. Cognitive Function</h3>
                            <ul>
                                <li>Impaired concentration</li>
                                <li>Intrusive thoughts disrupting focus</li>
                            </ul>

                            <h2>How Is OCD Diagnosed and Evaluated?</h2>
                            <p>Diagnosis is conducted by a qualified mental health professional using:</p>
                            <ul>
                                <li>Clinical interviews</li>
                                <li>Diagnostic criteria (DSM-5)</li>
                                <li>Severity scales such as the Yale-Brown Obsessive Compulsive Scale (Y-BOCS)</li>
                            </ul>
                            <p>Proper diagnosis is essential not only for treatment but also for legal and disability documentation.</p>

                            <h2>Treatment Options for OCD</h2>
                            <p>OCD is highly treatable, even in severe cases. Evidence-based treatments include:</p>

                            <h3>1. Cognitive Behavioral Therapy (CBT)</h3>
                            <p>Specifically Exposure and Response Prevention (ERP):</p>
                            <ul>
                                <li>Gradual exposure to feared triggers</li>
                                <li>Prevention of compulsive responses</li>
                            </ul>

                            <h3>2. Medication</h3>
                            <ul>
                                <li>SSRIs (first-line pharmacological treatment)</li>
                                <li>Augmentation strategies for resistant cases</li>
                            </ul>

                            <h3>3. Advanced Treatments</h3>
                            <p>For treatment-resistant OCD, <a href="blog-deep-tms-science.php" class="content-link">Deep TMS therapy</a> and other advanced options are available:</p>
                            <ul>
                                <li>Transcranial Magnetic Stimulation (TMS)</li>
                                <li>Ketamine-based therapies (in select cases)</li>
                            </ul>
                            <p>These options are available at specialized centers like Resiliency Mind+Body Medicine. For understanding costs, see our <a href="blog-deep-tms-cost.php" class="content-link">comprehensive cost guide</a>.</p>

                            <h2>Can OCD Improve Enough to No Longer Be Disabling?</h2>
                            <p>Yes. With appropriate treatment:</p>
                            <ul>
                                <li>Symptoms can significantly reduce</li>
                                <li>Functioning can improve</li>
                                <li>Many individuals return to work and normal routines</li>
                            </ul>
                            <p>Disability status is not always permanent and may change with effective care.</p>

                            <h2>Frequently Asked Questions (FAQs)</h2>

                            <div class="faq-item">
                                <h3>1. Is OCD always considered a disability?</h3>
                                <p>No. OCD is only considered a disability when it significantly impairs daily functioning or limits major life activities.</p>
                            </div>

                            <div class="faq-item">
                                <h3>2. Can I get workplace accommodations for OCD?</h3>
                                <p>Yes. Under the Americans with Disabilities Act, individuals with qualifying OCD can request reasonable accommodations.</p>
                            </div>

                            <div class="faq-item">
                                <h3>3. Does OCD qualify for Social Security disability benefits?</h3>
                                <p>It can, but only in severe cases where the condition prevents consistent employment and is well-documented medically.</p>
                            </div>

                            <div class="faq-item">
                                <h3>4. How do I prove OCD is disabling?</h3>
                                <p>Documentation from a licensed mental health professional, treatment history, and evidence of functional impairment are required.</p>
                            </div>

                            <div class="faq-item">
                                <h3>5. Can OCD be cured?</h3>
                                <p>OCD is typically a chronic condition, but it is highly manageable with proper treatment, and many patients experience significant improvement. Learn about <a href="blog-deep-tms-science.php" class="content-link">advanced treatment options</a> that can help.</p>
                            </div>

                            <div class="faq-item">
                                <h3>6. What is the most effective treatment for OCD?</h3>
                                <p>Exposure and Response Prevention (ERP), a form of CBT, is considered the gold standard, often combined with medication or <a href="blog-spravato-insurance.php" class="content-link">advanced therapies like TMS</a> when needed.</p>
                            </div>

