                            <h2>What Conditions Can BrainsWay Deep TMS Treat?</h2>
                            <p>BrainsWay Deep TMS has received FDA clearances for several conditions.</p>
                            
                            <h3>Major Depressive Disorder (MDD)</h3>
                            <p>Deep TMS is widely used for adults with depression, particularly when symptoms have not adequately improved with antidepressant medications.</p>
                            
                            <h3>Obsessive-Compulsive Disorder (OCD)</h3>
                            <p>BrainsWay Deep TMS is FDA-cleared for OCD and may help reduce intrusive thoughts and compulsive behaviors.</p>
                            
                            <h3>Smoking Addiction</h3>
                            <p>Specific Deep TMS protocols have been approved to help individuals reduce nicotine dependence and support smoking cessation efforts.</p>
                            
                            <h3>Depression with Anxiety Symptoms</h3>
                            <p>Many patients experiencing depression also struggle with significant <a href="blog-deep-tms-anxiety" class="content-link">anxiety symptoms</a>. Deep TMS may help address both when clinically appropriate.</p>
                            
                            <h3>Treatment-Resistant Depression</h3>
                            <p>Individuals who have tried multiple medications without achieving meaningful improvement are often candidates for Deep TMS evaluation.</p>

