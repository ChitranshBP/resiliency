                                <li>Emotional dysregulation</li>
                                <li>Anxiety or mood-related concerns</li>
                                <li>Repetitive behaviors</li>
                                <li>Social communication challenges</li>
                            </ul>
                            <p>TMS is typically used as a supportive therapy and may be combined with behavioral therapy, counseling, or other interventions.</p>
