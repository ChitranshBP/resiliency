                            <h2>What is Mental Health Awareness Month?</h2>
                            <p>Mental Health Awareness Month is a national initiative dedicated to:</p>
                            <ul>
                                <li>Raising awareness about mental health conditions</li>
                                <li>Educating the public about treatment options</li>
                                <li>Reducing stigma around seeking help</li>
                                <li>Encouraging early intervention</li>
                            </ul>
                            <p>It serves as a reminder that mental health is just as important as physical health—and that support is available.</p>

                            <h2>How Does Mental Health Awareness Month Work?</h2>
                            <p>Throughout the month, organizations, clinics, and communities:</p>
                            <ul>
                                <li>Share educational resources</li>
                                <li>Promote open conversations about mental health</li>
                                <li>Encourage screenings and early diagnosis</li>
                                <li>Highlight available treatments and support systems</li>
                            </ul>

